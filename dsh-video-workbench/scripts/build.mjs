#!/usr/bin/env node
/**
 * Build both plugin halves from src/ into the package root.
 *
 * - host: ESM bundle, Node builtins external.
 * - client: CJS bundle wrapped in the DSH lazy-CJS module-loader factory, with
 *   `react` external so the page's module table supplies it.
 */
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import { build } from 'esbuild'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const MARKER = '// Generated by scripts/build.mjs from src/ — do not edit.\n'
const manifest = JSON.parse(await readFile(path.join(ROOT, 'package.json'), 'utf8'))
/** The lazy-CJS module id must equal the package name. */
if (typeof manifest.name !== 'string' || manifest.name.length === 0) {
  throw new Error('package.json 缺少 name，无法确定 DSH 模块 id')
}
const PLUGIN_ID = manifest.name

async function buildHost() {
  const result = await build({
    entryPoints: [path.join(ROOT, 'src/host/index.ts')],
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: 'node20',
    external: ['node:*'],
    write: false,
    logLevel: 'warning',
  })
  await writeFile(path.join(ROOT, 'index.js'), MARKER + result.outputFiles[0].text, 'utf8')
}

async function buildClient() {
  const result = await build({
    entryPoints: [path.join(ROOT, 'src/client/index.tsx')],
    bundle: true,
    format: 'cjs',
    platform: 'browser',
    target: 'chrome120',
    external: ['react'],
    jsx: 'transform',
    jsxFactory: 'React.createElement',
    jsxFragment: 'React.Fragment',
    write: false,
    logLevel: 'warning',
  })
  const code = result.outputFiles[0].text
  const wrapped = [
    MARKER.trimEnd(),
    'window.__ModuleLoader__.load({',
    `  id: ${JSON.stringify(PLUGIN_ID)},`,
    '  factory(require) {',
    '    var module = { exports: {} };',
    '    var exports = module.exports;',
    code,
    '    // src/client/index.tsx uses `export default`; the plugin module DSH',
    '    // expects is that default export, not the CJS namespace object.',
    '    var exported = module.exports;',
    '    return exported && exported.__esModule && exported.default !== undefined',
    '      ? exported.default',
    '      : exported;',
    '  },',
    '});',
    '',
  ].join('\n')
  await writeFile(path.join(ROOT, 'client.js'), wrapped, 'utf8')
}

await buildHost()
await buildClient()
console.log('built index.js and client.js')
