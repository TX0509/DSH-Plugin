// Structural types for the DSH surfaces this plugin touches.
// Deliberately hand-written: importing any `@deepseek-ai/*` package would make
// the plugin break on a DSH upgrade, and those packages are not resolvable here.

import type { IncomingMessage, ServerResponse } from 'node:http'

export interface PeerLike {
  principal?: { kind?: string }
}

export interface IndexInjection {
  kind: 'global'
  name: string
  value: unknown
}

export interface WebRoute {
  kind: 'exact' | 'prefix'
  path: string
  handler: (request: IncomingMessage, response: ServerResponse) => void
}

export interface WebContext {
  webServer: {
    register(route: WebRoute): () => void
    /**
     * Root URL local clients use to reach the bound listener.
     * Throws before the listener binds a port.
     */
    getOrigin(): string
  }
  on(
    event: 'webserver/index-inject',
    listener: (table: IndexInjection[], peer?: PeerLike) => void,
  ): () => void
  effect(callback: () => (() => void) | undefined, label?: string): () => void
}

export interface HostContext {
  inject(dependencies: string[], callback: (ctx: WebContext) => void): void
  /** Optional in some profiles; features using it degrade to no-ops. */
  effect?(callback: () => (() => void) | undefined, label?: string): () => void
  logger?: {
    info(message: string): void
    error(message: string): void
  }
}

export interface ClientSlotContext {
  effect(callback: () => (() => void) | undefined, label?: string): () => void
  slots: {
    inject(ownerKey: string, callback: () => () => void): void
    register(options: { name: string; id: string; order?: number }, component: unknown): () => void
  }
}

