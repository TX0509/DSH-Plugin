#!/usr/bin/env node
/**
 * One-command check: typecheck -> DSH boundary -> build -> artifact consistency
 * -> syntax -> tests.
 *
 * The artifact step fails when the committed index.js / client.js differ from a
 * fresh build, which is what keeps DSH from loading stale code.
 */
import { spawnSync } from 'node:child_process'
import { readdirSync, readFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const node = process.execPath
const tsc = path.join(ROOT, 'node_modules', 'typescript', 'bin', 'tsc')

function run(label, command, args) {
  const result = spawnSync(command, args, { cwd: ROOT, stdio: 'inherit' })
  if (result.status !== 0) {
    console.error(`\n[verify] ${label} failed (exit ${String(result.status)})`)
    process.exit(result.status ?? 1)
  }
  console.log(`[verify] ${label} ok`)
}

/**
 * Keep DSH coupling inside the adapter layer.
 *
 * - `shared/dsh.ts` is the hand-written type declaration module, so it names
 *   the services but runs no calls.
 * - `shared/routes.ts` is the wire contract, so it owns the page-global name.
 * - Everything else outside `adapters/` must not touch either.
 */
function checkDshBoundary() {
  const callPattern = /webServer|__ModuleLoader__|slots\./u
  const wirePattern = /__DSH_VIDEO_WORKBENCH__/u
  const offenders = []
  for (const relative of readdirSync(path.join(ROOT, 'src'), { recursive: true })) {
    const name = String(relative).replaceAll('\\', '/')
    if (!name.endsWith('.ts') && !name.endsWith('.tsx')) continue
    const adapter = name.includes('adapters/')
    const source = readFileSync(path.join(ROOT, 'src', name), 'utf8')
    if (!adapter && name !== 'shared/dsh.ts' && callPattern.test(source)) offenders.push(name)
    if (!adapter && name !== 'shared/dsh.ts' && name !== 'shared/routes.ts' && wirePattern.test(source)) {
      offenders.push(name)
    }
  }
  if (offenders.length > 0) {
    console.error(`\n[verify] dsh boundary failed: ${[...new Set(offenders)].join(', ')}`)
    process.exit(1)
  }
  console.log('[verify] dsh boundary ok')
}

/**
 * Assert the built artifacts have the shape DSH loads. `git diff` proves they
 * match src/, but not that the build used the right transforms:
 * - both files carry the generation marker;
 * - no automatic JSX runtime (the page's module table only has `react`);
 * - the client registers exactly once, through the lazy-CJS loader, under the
 *   package name;
 * - the host bundle really is an ESM module that exports `apply` (importing the
 *   code DSH imports also proves it has no import-time side effects).
 */
async function checkArtifactShape() {
  const manifest = JSON.parse(readFileSync(path.join(ROOT, 'package.json'), 'utf8'))
  const host = readFileSync(path.join(ROOT, 'index.js'), 'utf8')
  const client = readFileSync(path.join(ROOT, 'client.js'), 'utf8')
  const failures = []
  for (const [name, text] of [['index.js', host], ['client.js', client]]) {
    if (!text.startsWith('// Generated by scripts/build.mjs')) failures.push(`${name}: 缺少构建标记`)
    if (/react\/jsx-runtime/u.test(text)) failures.push(`${name}: 使用了 automatic JSX runtime`)
  }
  const loadCount = (client.match(/window\.__ModuleLoader__\.load\(/gu) ?? []).length
  if (loadCount !== 1) failures.push(`client.js: 期望 1 次模块注册，实际 ${loadCount}`)
  const id = /id:\s*"([^"]+)"/u.exec(client)?.[1]
  if (id !== String(manifest.name)) {
    failures.push(`client.js: 模块 id（${String(id)}）与包名（${String(manifest.name)}）不一致`)
  }
  try {
    const hostModule = await import(pathToFileURL(path.join(ROOT, 'index.js')).href)
    if (typeof hostModule.apply !== 'function') failures.push('index.js: 缺少 apply 导出')
  } catch (error) {
    failures.push(`index.js: 无法按 ESM 引入（${String(error)}）`)
  }
  if (failures.length > 0) {
    console.error(`\n[verify] artifact shape failed: ${failures.join('；')}`)
    process.exit(1)
  }
  console.log('[verify] artifact shape ok')
}

run('typecheck', node, [tsc, '--noEmit'])
checkDshBoundary()
run('build', node, ['scripts/build.mjs'])
await checkArtifactShape()
// Compared against HEAD, not just the index: staging a stale artifact must not
// satisfy the check; the build outputs have to be committed with the source.
run('artifact consistency', 'git', ['diff', '--exit-code', 'HEAD', '--', 'index.js', 'client.js'])
run('syntax: index.js', node, ['--check', 'index.js'])
run('syntax: client.js', node, ['--check', 'client.js'])
run('tests', node, ['--test'])
console.log('[verify] all checks passed')
